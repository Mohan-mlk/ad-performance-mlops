"""Publish this project's datasets, release artifacts, and metrics to DagsHub MLflow.

All data generated by this repository is synthetic. The run records dataset
profiles/lineage and uploads the corresponding Parquet files as run artifacts.
"""
from __future__ import annotations

import hashlib
import json
import math
import sys
from pathlib import Path

import dagshub
import mlflow
import pandas as pd
import yaml
from mlflow.tracking import MlflowClient


ROOT = Path(__file__).resolve().parents[1]
EXPERIMENT_NAME = "asr-ad-performance"
TRACKING_URI = "https://dagshub.com/Mohan-mlk/ad-performance-mlops.mlflow"


def log_dataset(frame: pd.DataFrame, *, name: str, path: Path, context: str,
                digest: str, row_count: int, target: str | None = None) -> None:
    """Log a bounded profile so MLflow dataset metadata stays quick to compute."""
    from adperf import config as C

    sample_stride = max(1, (len(frame) + 999) // 1000)
    sample = frame.iloc[::sample_stride].copy()
    for column in C.CATEGORICAL_FEATURES:
        if column in sample:
            sample[column] = sample[column].astype("string").fillna("")
    dataset = mlflow.data.from_pandas(
        sample,
        name=name,
        source=path.resolve().as_uri(),
        digest=digest[:32],
        targets=target if target and target in sample else None,
    )
    mlflow.log_input(
        dataset,
        context=context,
        tags={
            "dataset_is_synthetic": "true",
            "source_sha256": digest,
            "source_row_count": str(row_count),
            "metadata_sample_rows": str(len(sample)),
        },
    )


def main() -> None:
    sys.path.insert(0, str(ROOT / "src"))
    dagshub.init(
        repo_owner="Mohan-mlk",
        repo_name="ad-performance-mlops",
        root=str(ROOT),
        mlflow=True,
    )

    from adperf import config as C
    from adperf.features import build as feature_builder

    raw_path = ROOT / "data" / "raw" / "ad_events.parquet"
    weekly_path = ROOT / "data" / "processed" / "weekly.parquet"
    metrics_path = ROOT / "artifacts" / "metrics.json"
    params_path = ROOT / "params.yaml"
    for required in (raw_path, weekly_path, metrics_path, params_path):
        if not required.is_file():
            raise FileNotFoundError(f"Required project output is missing: {required}")

    with params_path.open(encoding="utf-8") as stream:
        config = yaml.safe_load(stream)
    with metrics_path.open(encoding="utf-8") as stream:
        raw_metrics = json.load(stream)
    metrics = {
        str(key): float(value)
        for key, value in raw_metrics.items()
        if isinstance(value, (int, float)) and math.isfinite(value)
    }

    raw = pd.read_parquet(raw_path)
    weekly = pd.read_parquet(weekly_path)
    for column in C.CATEGORICAL_FEATURES:
        if column in weekly:
            weekly[column] = weekly[column].astype("category")
    train_df, valid_df, test_df = feature_builder.time_split(
        weekly,
        valid_days=int(config["train"]["valid_days"]),
        test_days=int(config["train"]["test_days"]),
    )
    raw_digest = hashlib.sha256(raw_path.read_bytes()).hexdigest()
    weekly_digest = hashlib.sha256(weekly_path.read_bytes()).hexdigest()
    params = {
        "run_type": "project_release_lineage",
        "dataset_is_synthetic": True,
        "raw_dataset_rows": len(raw),
        "weekly_dataset_rows": len(weekly),
        "raw_dataset_sha256": raw_digest,
        "weekly_dataset_sha256": weekly_digest,
        "data_seed": config["data"]["seed"],
        "data_rows_configured": config["data"]["rows"],
        "history_window_weeks": config["features"]["history_window_weeks"],
        **{f"train_{key}": value for key, value in config["train"].items()},
    }

    client = MlflowClient()
    experiment = client.get_experiment_by_name(EXPERIMENT_NAME)
    experiment_id = experiment.experiment_id if experiment else client.create_experiment(EXPERIMENT_NAME)
    run = client.create_run(
        experiment_id,
        run_name="project-release-with-datasets",
        tags={
            "source": "project-release-bundle",
            "model": "ad-performance-predictor",
            "dataset": "synthetic-ad-events-and-weekly-features",
            "project_integration_version": "1",
            "description": "Project datasets, chronological splits, release model, metrics, and monitoring artifacts.",
        },
    )
    run_id = run.info.run_id
    try:
        with mlflow.start_run(run_id=run_id):
            mlflow.log_params({str(key): str(value) for key, value in params.items()})
            mlflow.log_metrics(metrics)

            log_dataset(raw, name="ad-performance-raw-ad-events", path=raw_path,
                        context="source", digest=raw_digest, row_count=len(raw), target=C.TARGET)
            for context, split_name, frame in (
                ("training", "train", train_df),
                ("validation", "validation", valid_df),
                ("testing", "test", test_df),
            ):
                split = frame[[*C.FEATURES, C.TARGET]]
                log_dataset(split, name=f"ad-performance-weekly-{split_name}",
                            path=weekly_path, context=context, digest=weekly_digest,
                            row_count=len(split), target=C.TARGET)

            mlflow.log_artifact(str(raw_path), artifact_path="datasets/source")
            mlflow.log_artifact(str(weekly_path), artifact_path="datasets/weekly")
            for filename in (
                "model.joblib", "metrics.json", "feature_importance.csv",
                "insights.json", "drift_report.json", "backtest_summary.json",
            ):
                artifact = ROOT / "artifacts" / filename
                if artifact.is_file():
                    mlflow.log_artifact(str(artifact), artifact_path="project-release")
            reference = ROOT / "data" / "reference" / "reference_window.parquet"
            if reference.is_file():
                mlflow.log_artifact(str(reference), artifact_path="project-release/reference")

            mlflow.log_dict(
                {
                    "project": "ad-performance-mlops",
                    "experiment": EXPERIMENT_NAME,
                    "data_is_synthetic": True,
                    "target": C.TARGET,
                    "features": C.FEATURES,
                    "datasets": {
                        "raw": {"path": "data/raw/ad_events.parquet", "rows": len(raw), "sha256": raw_digest},
                        "weekly": {"path": "data/processed/weekly.parquet", "rows": len(weekly), "sha256": weekly_digest},
                        "train_rows": len(train_df),
                        "validation_rows": len(valid_df),
                        "test_rows": len(test_df),
                    },
                },
                "lineage/project_run_manifest.json",
            )
        client.set_terminated(run_id, status="FINISHED")
    except Exception:
        client.set_terminated(run_id, status="FAILED")
        raise

    print(f"Finished DagsHub MLflow run: {run_id}")
    print(f"{TRACKING_URI}/#/experiments/{experiment_id}/runs/{run_id}")


if __name__ == "__main__":
    main()
